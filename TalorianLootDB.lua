-- Определение сложности рейда/данжа по ilvl и флагу "Героический" из тултипа
function TalorianLootDB:DetermineDifficulty(zId, itemId, ilvl, isHeroicTooltip)
    local zInfo = self.Zones[zId]
    if not zInfo then return 1 end

    -- 1. Точное предвычисленное значение из PrimeAttuneCore.ItemMeta
    local pac = rawget(_G, "PrimeAttuneCore")
    if pac and pac.ItemMeta and pac.ItemMeta[itemId] then
        local metaDiff = pac.ItemMeta[itemId][5]
        if metaDiff and metaDiff >= 1 and metaDiff <= 4 then
            return metaDiff
        end
    end

    ilvl = tonumber(ilvl) or 0
    if ilvl == 0 and type(GetItemInfo) == "function" then
        local _, _, _, infoIlvl = GetItemInfo(itemId)
        ilvl = tonumber(infoIlvl) or 0
    end

    if not zInfo.isRaid then
        -- Подземелья на 5 человек: 1 = Обычный, 2 = Героический
        if zInfo.exp == "Classic" then return 1 end
        if isHeroicTooltip then return 2 end
        if zInfo.exp == "WotLK" then
            if zId == 4723 then
                return (ilvl >= 219) and 2 or 1
            elseif zId == 4809 or zId == 4813 or zId == 4820 then
                return (ilvl >= 232) and 2 or 1
            else
                return (ilvl >= 200) and 2 or 1
            end
        end
        if zInfo.exp == "TBC" and ilvl >= 115 and (itemId >= 27400 and itemId <= 35600) then
            local _, _, q = GetItemInfo(itemId)
            if q == 4 then return 2 end
        end
        return 1
    end

    -- Классика и TBC рейды
    if zInfo.exp == "Classic" then
        return (zId == 1977 or zId == 3429) and 1 or 2
    elseif zInfo.exp == "TBC" then
        return (zId == 3457 or zId == 3805) and 1 or 2
    end

    -- Рейды WotLK с 4 сложностями: ЦЛК (4812), ИК (4722), РС (4987)
    if zId == 4812 then
        -- Цитадель Ледяной Короны:
        -- 10 об: 251 (258 у Короля-лича)
        -- 25 об: 264 (271 у Короля-лича) БЕЗ надписи "Героический"
        -- 10 гер: 264 (271 у Короля-лича) С надписью "Героический"
        -- 25 гер: 277 (284 у Короля-лича) С надписью "Героический"
        if (itemId >= 50600 and itemId <= 50738) or (itemId >= 51210 and itemId <= 51315) or ilvl >= 277 then
            return 4 -- 25 гер
        elseif isHeroicTooltip then
            if ilvl >= 277 then return 4 end
            return 3 -- 10 гер
        elseif ilvl == 264 or ilvl == 271 then
            if (itemId >= 51782 and itemId <= 51950) then
                return 3 -- 10 гер (диапазон ID 10 гер ЦЛК)
            end
            return 2 -- 25 об
        elseif ilvl == 251 or ilvl == 258 then
            return 1 -- 10 об
        elseif (itemId >= 49908 and itemId <= 50189) or (itemId >= 50350 and itemId <= 50470) or (itemId >= 51125 and itemId <= 51209) then
            return 2 -- 25 об
        elseif itemId >= 51782 and itemId <= 51950 then
            return 3 -- 10 гер
        end
        return 1
    elseif zId == 4987 then
        -- Рубиновое святилище: 10 об (258), 25 об (271), 10 гер (271 гер), 25 гер (284 гер)
        if ilvl >= 284 or (itemId >= 54578 and itemId <= 54592) then
            return 4
        elseif isHeroicTooltip then
            return 3
        elseif ilvl == 271 or (itemId >= 54556 and itemId <= 54577) then
            return 2
        end
        return 1
    elseif zId == 4722 then
        -- Испытание крестоносца: 10 об (232), 25 об (245), 10 гер (245 гер), 25 гер (258 гер)
        if ilvl >= 258 then
            return 4
        elseif isHeroicTooltip then
            return 3
        elseif ilvl == 245 then
            if itemId >= 47729 then return 3 end
            return 2
        end
        return 1
    else
        -- 2-режимные рейды WotLK (Ульдуар 4273, Наксрамас 3456, Око 4500, ОС 4493, СА 4603, Ониксия 2159)
        if zId == 4273 then
            return (ilvl >= 226) and 2 or 1
        elseif zId == 3456 then
            if itemId >= 39723 and itemId <= 40414 then return 2 end
            return (ilvl >= 213) and 2 or 1
        elseif zId == 4500 or zId == 4493 then
            return (ilvl >= 213) and 2 or 1
        elseif zId == 4603 then
            return (ilvl >= 213) and 2 or 1
        elseif zId == 2159 then
            return (ilvl >= 245) and 2 or 1
        end
    end

    return 1
end

function TalorianLootDB:FormatSourceLabel(zId, dId)
    local zInfo = self.Zones[zId]
    if not zInfo then return nil end
    if zInfo.isRaid then
        if zInfo.exp == "Classic" then
            return zInfo.short
        elseif zInfo.exp == "TBC" then
            return zInfo.short .. ((zId == 3457 or zId == 3805) and " 10" or " 25")
        else
            local dLabels = { "10об", "25об", "10г", "25г" }
            return zInfo.short .. " " .. (dLabels[dId or 1] or "10об")
        end
    else
        if zInfo.exp == "Classic" then
            return zInfo.short
        else
            return zInfo.short .. ((dId == 2) and " Гер" or " Об")
        end
    end
end

-- Комплексный определитель зоны, сложности и подписи для любого itemId
function TalorianLootDB:ResolveItem(itemId, ilvl, isHeroicTooltip, serverZoneMap)
    if not itemId then return nil, nil, nil end

    -- 1. Точный серверный пакет ASMSG_ATC_ZONE (если уже получен)
    if serverZoneMap and serverZoneMap[itemId] then
        for zid, srvDiff in pairs(serverZoneMap[itemId]) do
            if self.Zones[zid] then
                local dId = self:DetermineDifficulty(zid, itemId, ilvl, isHeroicTooltip) or srvDiff or 1
                return zid, dId, self:FormatSourceLabel(zid, dId)
            end
        end
    end

    -- 2. Энкаунтеры из WCollections (учитывает ведущий '0' как флаг Героической сложности 10гер/25гер!)
    local wc = rawget(_G, "WCollections")
    if wc and type(wc) == "table" and wc.Cache and wc.Cache.All then
        local skin = wc.Cache.All[itemId]
        local bStr = nil
        if type(skin) == "string" then
            local parts = {}
            for b in skin:gmatch("B([0-9]+)") do table.insert(parts, b) end
            if #parts > 0 then bStr = table.concat(parts, ",") end
        elseif type(skin) == "table" and skin.SourceBosses then
            bStr = type(skin.SourceBosses) == "table" and table.concat(skin.SourceBosses, ",") or tostring(skin.SourceBosses)
        end
        if bStr then
            for token in bStr:gmatch("([^,]+)") do
                local isDynHeroic = (token:sub(1, 1) == "0" or token:sub(1, 1) == "-")
                local encId = math.abs(tonumber(token) or 0)
                local eInfo = self.Encounters[encId]
                if eInfo and self.Zones[eInfo.z] then
                    local zId = eInfo.z
                    local zMeta = self.Zones[zId]
                    local dId = eInfo.d or 1
                    if zMeta.isRaid and (zId == 4812 or zId == 4722 or zId == 4987) then
                        if isDynHeroic or isHeroicTooltip then
                            dId = (eInfo.d == 2) and 4 or 3
                        else
                            dId = eInfo.d
                        end
                        -- Дополнительная сверка по ilvl (например, 277 в ЦЛК всегда 25 гер)
                        local det = self:DetermineDifficulty(zId, itemId, ilvl, isHeroicTooltip or isDynHeroic)
                        if det then dId = det end
                    elseif not zMeta.isRaid then
                        if isDynHeroic or isHeroicTooltip or eInfo.d >= 2 then dId = 2 else dId = 1 end
                    end
                    return zId, dId, self:FormatSourceLabel(zId, dId)
                end
            end
        end
    end

    -- 3. Прямое попадание в нашу очищенную таблицу предметов подземелий и рейдов (TalorianLootDB.InstanceItems)
    local staticZone = self.InstanceItems[itemId]
    if staticZone and self.Zones[staticZone] then
        local dId = self:DetermineDifficulty(staticZone, itemId, ilvl, isHeroicTooltip)
        return staticZone, dId, self:FormatSourceLabel(staticZone, dId)
    end

    -- 4. Диапазоны ID для рейдов и подземелий WotLK (ЦЛК 25об/10гер/25гер, РС, ИК, Ульдуар, Накс, Кузня/Яма/Залы)
    -- Цитадель Ледяной Короны (4812)
    if (itemId >= 49888 and itemId <= 50189)
        or (itemId >= 50339 and itemId <= 50470)
        or (itemId >= 50600 and itemId <= 50738)
        or (itemId >= 50759 and itemId <= 51025)
        or (itemId >= 51125 and itemId <= 51315)
        or (itemId >= 51325 and itemId <= 51387)
        or (itemId >= 51561 and itemId <= 51566)
        or (itemId >= 51782 and itemId <= 52030)
        or itemId == 52572 then
        local dId = self:DetermineDifficulty(4812, itemId, ilvl, isHeroicTooltip)
        return 4812, dId, self:FormatSourceLabel(4812, dId)
    end

    -- Рубиновое святилище (4987)
    if (itemId >= 53110 and itemId <= 53500) or (itemId >= 54556 and itemId <= 54592) then
        local dId = self:DetermineDifficulty(4987, itemId, ilvl, isHeroicTooltip)
        return 4987, dId, self:FormatSourceLabel(4987, dId)
    end

    -- Испытание крестоносца (4722)
    if (itemId >= 46958 and itemId <= 47559) or (itemId >= 47729 and itemId <= 48027) then
        local dId = self:DetermineDifficulty(4722, itemId, ilvl, isHeroicTooltip)
        return 4722, dId, self:FormatSourceLabel(4722, dId)
    end

    -- Ульдуар (4273)
    if (itemId >= 45106 and itemId <= 46099) or (itemId >= 46340 and itemId <= 46351) then
        local dId = self:DetermineDifficulty(4273, itemId, ilvl, isHeroicTooltip)
        return 4273, dId, self:FormatSourceLabel(4273, dId)
    end

    -- Наксрамас (3456), Око Вечности (4500), Обсидиановое святилище (4493)
    if (itemId >= 39139 and itemId <= 39473) or (itemId >= 39723 and itemId <= 40414) then
        local dId = self:DetermineDifficulty(3456, itemId, ilvl, isHeroicTooltip)
        return 3456, dId, self:FormatSourceLabel(3456, dId)
    elseif (itemId >= 40426 and itemId <= 40459) or (itemId >= 40525 and itemId <= 40532) then
        local dId = self:DetermineDifficulty(4500, itemId, ilvl, isHeroicTooltip)
        return 4500, dId, self:FormatSourceLabel(4500, dId)
    elseif (itemId >= 40460 and itemId <= 40490) or (itemId >= 40549 and itemId <= 40590) or (itemId >= 43986 and itemId <= 44011) then
        local dId = self:DetermineDifficulty(4493, itemId, ilvl, isHeroicTooltip)
        return 4493, dId, self:FormatSourceLabel(4493, dId)
    end

    return nil, nil, nil
end
